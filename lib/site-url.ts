// =====================================================================
//  PRODUCTION ORIGIN — the one place the site's public address is read.
// =====================================================================
//
// The address comes from the Lalitha_Barri_WEBSITE_URL environment
// variable, set in Vercel → Project → Settings → Environment Variables
// (Production). Its value must be a plain https address with no brackets
// or quotes, e.g. https://www.example-domain.com (illustration only).
// To change the domain later, change that variable and redeploy — no code
// changes are needed. Never hard-code a URL here.
//
// Server-only: the variable deliberately has no NEXT_PUBLIC_ prefix, so it
// is never sent to the browser. This module may only be imported by
// server code (layouts, pages' metadata, sitemap, robots); the
// "server-only" import below makes the build fail if a client component
// tries.
//
// What uses it:
//   • metadataBase (app/layout.tsx) → absolute Open Graph / Twitter URLs
//   • pageMetadata() below → each page's own canonical URL and og:url
//   • app/sitemap.ts and app/robots.ts
//
// Safety: a Vercel *production* build without the variable fails with a
// clear error instead of publishing localhost URLs. Preview deployments
// and local builds without it simply omit canonical URLs and the sitemap.

import "server-only";
import type { Metadata } from "next";
import { siteTitle } from "@/content/site";

/** Name of the environment variable holding the production origin. */
export const SITE_URL_ENV = "Lalitha_Barri_WEBSITE_URL";

function parseOrigin(value: string): URL {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`${SITE_URL_ENV} is not a valid URL (no brackets or quotes): "${value}"`);
  }
  if (url.protocol !== "https:" && url.hostname !== "localhost") {
    throw new Error(`${SITE_URL_ENV} must use https: "${value}"`);
  }
  // Keep only the origin (drops any path, query or trailing slash).
  return new URL(url.origin);
}

const raw = process.env.Lalitha_Barri_WEBSITE_URL?.trim();

/** The production origin, or undefined when the variable isn't set. */
export const siteUrl: URL | undefined = raw ? parseOrigin(raw) : undefined;

/** True only for Vercel's production deployments. */
export const isVercelProduction = process.env.VERCEL_ENV === "production";

if (!siteUrl && isVercelProduction) {
  throw new Error(
    `${SITE_URL_ENV} must be set for production deployments (Vercel → Settings → Environment Variables).`,
  );
}

/** Absolute URL for a site path, e.g. absoluteUrl("/work"). */
export function absoluteUrl(path: string): string | undefined {
  return siteUrl ? new URL(path, siteUrl).toString() : undefined;
}

type PageMetadataInput = {
  /** Path of this page, e.g. "/work". Used for its own canonical URL. */
  path: string;
  /** Short title; the layout adds " · Lalitha Barri". Omit for the homepage. */
  title?: string;
  /** Full title for sharing cards, e.g. "Work · Lalitha Barri". */
  socialTitle: string;
  description: string;
};

// The shared social card generated by app/opengraph-image.tsx and
// app/twitter-image.tsx. A page that defines its own `openGraph`/`twitter`
// objects replaces its parent's, so pageMetadata() attaches the card
// explicitly to keep it on every page.
const socialImage = { width: 1200, height: 630, alt: siteTitle };

/**
 * Metadata for one page: its own canonical URL plus matching Open Graph and
 * Twitter fields. Every public page calls this with ITS OWN path, so no page
 * points its canonical at the homepage.
 */
export function pageMetadata({ path, title, socialTitle, description }: PageMetadataInput): Metadata {
  return {
    ...(title ? { title } : {}),
    description,
    ...(siteUrl ? { alternates: { canonical: path } } : {}),
    openGraph: {
      type: "website",
      siteName: "Lalitha Barri",
      title: socialTitle,
      description,
      ...(siteUrl ? { url: path } : {}),
      images: [{ url: "/opengraph-image", type: "image/png", ...socialImage }],
    },
    twitter: {
      card: "summary_large_image",
      title: socialTitle,
      description,
      images: [{ url: "/twitter-image", ...socialImage }],
    },
  };
}
